import math
from cadquery import func as cf

def clutch_brick(rows, cols, height, stud_d, stud_h, spacing):
    length = cols * spacing - 0.2
    width = rows * spacing - 0.2
    brick = cf.box(length, width, height)
    stud = cf.cylinder(d=stud_d, h=stud_h)
    for i in range(cols):
        for j in range(rows):
            x = (i - (cols - 1) / 2) * spacing
            y = (j - (rows - 1) / 2) * spacing
            brick = brick + stud.moved(x=x, y=y, z=height)
    return brick

rows, cols = 2, 4
height, stud_d, stud_h, spacing = 9.6, 4.8, 1.7, 8.0
brick = clutch_brick(rows, cols, height, stud_d, stud_h, spacing)

body_vol = (cols * spacing - 0.2) * (rows * spacing - 0.2) * height
stud_vol = math.pi * (stud_d / 2) ** 2 * stud_h
expected = body_vol + rows * cols * stud_vol
assert abs(brick.Volume() - expected) < 0.5
brick.exportStl("brick.stl")



